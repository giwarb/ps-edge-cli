function Invoke-PseCdpAutoHandler {
    param(
        [Parameter(Mandatory = $true)]
        $Conn,

        [Parameter(Mandatory = $true)]
        $Message
    )

    if ($null -ne $Message.PSObject.Properties['id']) {
        return $false
    }

    if ($Message.method -eq 'Page.javascriptDialogOpening') {
        $dialogParams = $Message.params
        $response = Resolve-PseDialogResponse -Type $dialogParams.type -Policy $Conn.DialogPolicy -DefaultPrompt $dialogParams.defaultPrompt
        $handleParams = @{ accept = [bool]$response.accept }
        if ($null -ne $response.promptText) {
            $handleParams.promptText = [string]$response.promptText
        }

        try {
            if ($null -ne $Message.PSObject.Properties['sessionId']) {
                [void](Send-PseCdpFireAndForget -Conn $Conn -Method 'Page.handleJavaScriptDialog' -Params $handleParams -SessionId ([string]$Message.sessionId))
            } else {
                [void](Send-PseCdpFireAndForget -Conn $Conn -Method 'Page.handleJavaScriptDialog' -Params $handleParams)
            }
        } catch {
        }

        [void]$Conn.HandledDialogs.Add(@{
            type = [string]$dialogParams.type
            message = [string]$dialogParams.message
            accept = [bool]$response.accept
            promptText = $response.promptText
        })
        while ($Conn.HandledDialogs.Count -gt 100) {
            $Conn.HandledDialogs.RemoveAt(0)
        }

        return $true
    }

    if ($Message.method -eq 'Target.attachedToTarget') {
        $p = $Message.params
        if ($p.targetInfo.type -eq 'iframe' -or $p.targetInfo.type -eq 'page') {
            try {
                [void](Send-PseCdpFireAndForget -Conn $Conn -Method 'Page.enable' -SessionId ([string]$p.sessionId))
                [void](Send-PseCdpFireAndForget -Conn $Conn -Method 'Target.setAutoAttach' -Params @{
                    autoAttach = $true
                    waitForDebuggerOnStart = $false
                    flatten = $true
                } -SessionId ([string]$p.sessionId))
            } catch {
            }
        }
        return $true
    }

    return $false
}

function Send-PseCdp {
    param(
        [Parameter(Mandatory = $true)]
        $Conn,

        [Parameter(Mandatory = $true)]
        [string]$Method,

        [hashtable]$Params,

        [string]$SessionId,

        [int]$TimeoutSec = 30
    )

    $id = [int]$Conn.NextId
    $Conn.NextId = $id + 1

    $message = @{
        id = $id
        method = $Method
    }
    if ($PSBoundParameters.ContainsKey('Params')) {
        $message.params = $Params
    }
    if (-not [string]::IsNullOrEmpty($SessionId)) {
        $message.sessionId = $SessionId
    }

    $json = ConvertTo-PseJson $message
    $bytes = [System.Text.Encoding]::UTF8.GetBytes($json)
    $segment = [System.ArraySegment[byte]]::new($bytes)
    $cts = [System.Threading.CancellationTokenSource]::new()

    try {
        $cts.CancelAfter([int]($TimeoutSec * 1000))
        [void]$Conn.Socket.SendAsync($segment, [System.Net.WebSockets.WebSocketMessageType]::Text, $true, $cts.Token).GetAwaiter().GetResult()
    } catch [System.OperationCanceledException] {
        throw "Timed out after $TimeoutSec seconds sending CDP method $Method."
    } catch {
        if ($_.Exception.InnerException -is [System.OperationCanceledException]) {
            throw "Timed out after $TimeoutSec seconds sending CDP method $Method."
        }
        throw
    } finally {
        $cts.Dispose()
    }

    $deadline = [DateTime]::UtcNow.AddSeconds($TimeoutSec)
    while ([DateTime]::UtcNow -lt $deadline) {
        $remaining = [int][Math]::Ceiling(($deadline - [DateTime]::UtcNow).TotalSeconds)
        if ($remaining -lt 1) {
            $remaining = 1
        }

        $response = Receive-PseCdpMessage -Conn $Conn -TimeoutSec $remaining
        if ($null -eq $response) {
            continue
        }

        if (Invoke-PseCdpAutoHandler -Conn $Conn -Message $response) {
            continue
        }

        $idProperty = $response.PSObject.Properties['id']
        if ($null -eq $idProperty) {
            [void]$Conn.Events.Add($response)
            continue
        }

        if ([int]$response.id -ne $id) {
            continue
        }

        if ($null -ne $response.PSObject.Properties['error']) {
            $code = $response.error.code
            $errorMessage = $response.error.message
            throw "CDP error $code`: $errorMessage ($Method)"
        }

        return $response.result
    }

    throw "Timed out after $TimeoutSec seconds waiting for CDP response to $Method."
}

function Wait-PseCdpEvent {
    param(
        [Parameter(Mandatory = $true)]
        $Conn,

        [Parameter(Mandatory = $true)]
        [string]$EventName,

        [int]$TimeoutSec = 30
    )

    for ($i = 0; $i -lt $Conn.Events.Count; $i++) {
        $event = $Conn.Events[$i]
        if ($null -eq $event.PSObject.Properties['sessionId'] -and $event.method -eq $EventName) {
            $Conn.Events.RemoveAt($i)
            return $event.params
        }
    }

    $deadline = [DateTime]::UtcNow.AddSeconds($TimeoutSec)
    while ([DateTime]::UtcNow -lt $deadline) {
        $remaining = [int][Math]::Ceiling(($deadline - [DateTime]::UtcNow).TotalSeconds)
        if ($remaining -lt 1) {
            $remaining = 1
        }

        $message = Receive-PseCdpMessage -Conn $Conn -TimeoutSec $remaining
        if ($null -eq $message) {
            continue
        }

        if (Invoke-PseCdpAutoHandler -Conn $Conn -Message $message) {
            continue
        }

        $idProperty = $message.PSObject.Properties['id']
        if ($null -ne $idProperty) {
            continue
        }

        if ($null -eq $message.PSObject.Properties['sessionId'] -and $message.method -eq $EventName) {
            return $message.params
        }

        [void]$Conn.Events.Add($message)
    }

    throw "Timed out after $TimeoutSec seconds waiting for CDP event $EventName."
}

function Close-PseCdp {
    param(
        [Parameter(Mandatory = $true)]
        $Conn
    )

    try {
        if ($null -ne $Conn -and $null -ne $Conn.Socket) {
            if ($Conn.Socket.State -eq [System.Net.WebSockets.WebSocketState]::Open) {
                $cts = [System.Threading.CancellationTokenSource]::new()
                try {
                    $cts.CancelAfter(2000)
                    [void]$Conn.Socket.CloseAsync([System.Net.WebSockets.WebSocketCloseStatus]::NormalClosure, 'close', $cts.Token).GetAwaiter().GetResult()
                } catch {
                } finally {
                    $cts.Dispose()
                }
            }
            $Conn.Socket.Dispose()
        }
    } catch {
    }
}

