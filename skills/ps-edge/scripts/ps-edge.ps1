function ConvertTo-PseHashtable {
    param(
        [AllowNull()]
        $Value
    )

    if ($null -eq $Value) {
        return $null
    }

    if ($Value -is [System.Collections.IDictionary]) {
        $hash = @{}
        foreach ($key in $Value.Keys) {
            $hash[$key] = ConvertTo-PseHashtable -Value $Value[$key]
        }
        return $hash
    }

    if ($Value -is [pscustomobject]) {
        $hash = @{}
        foreach ($prop in $Value.PSObject.Properties) {
            $hash[$prop.Name] = ConvertTo-PseHashtable -Value $prop.Value
        }
        return $hash
    }

    if ($Value -is [System.Array] -and -not ($Value -is [string])) {
        $list = New-Object System.Collections.ArrayList
        foreach ($item in $Value) {
            [void]$list.Add((ConvertTo-PseHashtable -Value $item))
        }
        return @($list)
    }

    return $Value
}

function Invoke-PseHttpText {
    param(
        [Parameter(Mandatory = $true)]
        [int]$Port,

        [Parameter(Mandatory = $true)]
        [string]$Path,

        [string]$Method = 'GET'
    )

    $uri = "http://127.0.0.1:$Port$Path"
    $request = [System.Net.WebRequest]::Create($uri)
    $request.Proxy = $null
    $request.Method = $Method
    $request.KeepAlive = $false
    $request.Timeout = 5000

    $response = $null
    $stream = $null
    $reader = $null
    try {
        $response = $request.GetResponse()
        $stream = $response.GetResponseStream()
        $reader = New-Object System.IO.StreamReader($stream, [System.Text.Encoding]::UTF8)
        return $reader.ReadToEnd()
    } finally {
        if ($null -ne $reader) {
            $reader.Dispose()
        } elseif ($null -ne $stream) {
            $stream.Dispose()
        }
        if ($null -ne $response) {
            $response.Dispose()
        }
    }
}

