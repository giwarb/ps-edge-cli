function Connect-PseCdp {
    param(
        [Parameter(Mandatory = $true)]
        [string]$WebSocketUrl
    )

    $socket = New-Object System.Net.WebSockets.ClientWebSocket
    $socket.Options.Proxy = $null
    $cts = [System.Threading.CancellationTokenSource]::new()
    try {
        $cts.CancelAfter(30000)
        [void]$socket.ConnectAsync([Uri]$WebSocketUrl, $cts.Token).GetAwaiter().GetResult()
    } finally {
        $cts.Dispose()
    }

    [pscustomobject]@{
        Socket = $socket
        NextId = 1
        Events = New-Object System.Collections.ArrayList
        DialogPolicy = $null
        HandledDialogs = New-Object System.Collections.ArrayList
    }
}

function Receive-PseCdpMessage {
    param(
        [Parameter(Mandatory = $true)]
        $Conn,

        [int]$TimeoutSec = 30
    )

    $buffer = New-Object byte[] 65536
    $segment = [System.ArraySegment[byte]]::new($buffer)
    $stream = New-Object System.IO.MemoryStream
    $cts = [System.Threading.CancellationTokenSource]::new()

    try {
        $cts.CancelAfter([int]($TimeoutSec * 1000))

        do {
            try {
                $result = $Conn.Socket.ReceiveAsync($segment, $cts.Token).GetAwaiter().GetResult()
            } catch [System.OperationCanceledException] {
                throw "Timed out after $TimeoutSec seconds waiting for a CDP message."
            } catch {
                if ($_.Exception.InnerException -is [System.OperationCanceledException]) {
                    throw "Timed out after $TimeoutSec seconds waiting for a CDP message."
                }
                throw
            }

            if ($result.MessageType -eq [System.Net.WebSockets.WebSocketMessageType]::Close) {
                throw 'CDP WebSocket closed while waiting for a message.'
            }

            if ($result.Count -gt 0) {
                $stream.Write($buffer, 0, $result.Count)
            }
        } while (-not $result.EndOfMessage)

        $json = [System.Text.Encoding]::UTF8.GetString($stream.ToArray())
        if ([string]::IsNullOrWhiteSpace($json)) {
            return $null
        }
        return $json | ConvertFrom-Json
    } finally {
        $stream.Dispose()
        $cts.Dispose()
    }
}

function Resolve-PseDialogResponse {
    param(
        [string]$Type,

        [AllowNull()]
        $Policy,

        [AllowNull()]
        [string]$DefaultPrompt
    )

    $mode = 'dismiss'
    $policyText = $null
    if ($null -ne $Policy) {
        if ($Policy.mode -eq 'accept') {
            $mode = 'accept'
        }
        if ($null -ne $Policy.text) {
            $policyText = [string]$Policy.text
        }
    }

    if ($Type -eq 'beforeunload' -or $Type -eq 'alert') {
        return @{
            accept = $true
            promptText = $null
        }
    }

    $accept = ($mode -eq 'accept')
    if ($Type -eq 'prompt' -and $accept) {
        $promptText = ''
        if ($null -ne $policyText) {
            $promptText = $policyText
        } elseif ($null -ne $DefaultPrompt) {
            $promptText = $DefaultPrompt
        }
        return @{
            accept = $true
            promptText = $promptText
        }
    }

    return @{
        accept = $accept
        promptText = $null
    }
}

