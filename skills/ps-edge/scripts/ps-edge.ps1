function ConvertFrom-PseArgs {
    param(
        [Parameter(ValueFromRemainingArguments = $true)]
        [AllowNull()]
        [object[]]$Args
    )

    $positionals = New-Object System.Collections.ArrayList
    $options = @{}
    $flags = @{
        headless = $true
        attach = $true
        fullpage = $true
        right = $true
        double = $true
        submit = $true
        accept = $true
        acceptdialog = $true
        dismiss = $true
        rescue = $true
        waitdownload = $true
        noquietflags = $true
    }

    if ($null -ne $Args -and $Args.Count -eq 1 -and $Args[0] -is [System.Array] -and -not ($Args[0] -is [string])) {
        $Args = @($Args[0] | ForEach-Object { $_ })
    }

    $i = 0
    while ($null -ne $Args -and $i -lt $Args.Count) {
        $token = [string]$Args[$i]
        if ($token -match '^--?(.+)$') {
            $name = $Matches[1].ToLowerInvariant()
            if ($name -eq 'extraarg') {
                $values = $null
                if ($options.ContainsKey($name)) {
                    $values = $options[$name]
                } else {
                    $values = New-Object System.Collections.ArrayList
                    $options[$name] = $values
                }
                if (($i + 1) -lt $Args.Count) {
                    [void]$values.Add([string]$Args[$i + 1])
                    $i++
                } else {
                    [void]$values.Add('')
                }
            } elseif ($flags.ContainsKey($name)) {
                $options[$name] = $true
            } elseif (($i + 1) -lt $Args.Count -and (([string]$Args[$i + 1]) -notmatch '^-' -or ([string]$Args[$i + 1]) -match '^-\d+(?:\.\d+)?$')) {
                $options[$name] = [string]$Args[$i + 1]
                $i++
            } else {
                $options[$name] = $true
            }
        } else {
            [void]$positionals.Add($token)
        }
        $i++
    }

    @{
        Positional = $positionals
        Options = $options
    }
}

